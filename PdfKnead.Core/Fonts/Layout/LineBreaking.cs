using System.Globalization;

namespace PdfKnead.Core.Fonts.Layout;

/// <summary>What UAX #14 says about a position between two characters: no break, a break opportunity, a mandatory break.</summary>
internal enum LineBreakKind : byte
{
    /// <summary>No break (×).</summary>
    None,

    /// <summary>A break opportunity (÷).</summary>
    Allowed,

    /// <summary>A mandatory break (!).</summary>
    Mandatory,
}

/// <summary>
/// The break opportunities of a text after UAX #14, Unicode Line Breaking Algorithm, revision 53 (Unicode 16.0.0), with the classes of
/// LineBreak.txt 16.0.0 (<see cref="LineBreakClass"/>; generated by tools/schriftdaten/unicode_zeilenumbruch.py) and the rules LB1–LB31 in their
/// order: the conformance file LineBreakTest.txt 16.0.0 passes line by line. LB1 resolves AI, SG, XX to AL, SA to CM (Mn, Mc) or AL — no
/// dictionary, so Thai, Lao, Khmer, Myanmar and Tai Tham break at spaces and ZERO WIDTH SPACE only — and CJ to NS. One class is tailored (Lisu
/// punctuation, <see cref="Tailor"/>); Cham (syllables AS, finals and dandas BA) and Tibetan (tsheg BA, U+0F0C GL, shad EX) break after the
/// Unicode chapters with the classes of the file as they are.
/// <para>Besides, the places where an emergency break of a word too wide for its line may fall (outside the algorithm, UAX #14 section 3): only
/// at the boundaries of extended grapheme clusters (UAX #29, from the runtime), not inside the orthographic syllable of a Brahmic script (LB28a),
/// a pair of regional indicators (LB30a), an emoji with its modifier (LB30b), not after ZWJ (LB8a), not next to WJ (LB11), not after the
/// Mongolian vowel separator (it begins the new line, Unicode 13.5.1) and not before a Pau Cin Hau tone mark (Unicode 16.13.1).</para>
/// One pass over the text, a constant look back and ahead: linear time for any input; an unpaired surrogate counts as U+FFFD
/// (docs/FEHLERGEDAECHTNIS.md, No. 1192, 1196).
/// </summary>
internal static partial class LineBreaking
{
    private const int ClassMask = 63, EastAsianFlag = 1 << 6, PiFlag = 1 << 7, PfFlag = 1 << 8, MarkFlag = 1 << 9, PictographicFlag = 1 << 10;

    /// <summary>The generated value of a code point (class and flags, see <see cref="RangeValues"/>).</summary>
    private static ushort ValueOf(int codePoint)
    {
        if ((uint)codePoint > 0x10FFFF) return (ushort)LineBreakClass.XX;
        int lo = 0, hi = RangeStarts.Length - 1;
        while (lo < hi)
        {
            var mid = (lo + hi + 1) >> 1;
            if (RangeStarts[mid] <= codePoint) lo = mid;
            else hi = mid - 1;
        }
        return RangeValues[lo];
    }

    /// <summary>The property Line_Break of a code point as LineBreak.txt 16.0.0 gives it (before LB1).</summary>
    internal static LineBreakClass ClassOf(int codePoint) => (LineBreakClass)(ValueOf(codePoint) & ClassMask);

    /// <summary>Whether a code point has East_Asian_Width F, W or H ($EastAsian of UAX #14, section 6).</summary>
    internal static bool IsEastAsian(int codePoint) => (ValueOf(codePoint) & EastAsianFlag) != 0;

    /// <summary>The class after LB1: AI, SG, XX → AL; SA → CM for Mn and Mc, else AL; CJ → NS.</summary>
    internal static LineBreakClass Resolved(int codePoint) => Resolve(ValueOf(codePoint));

    private static LineBreakClass Resolve(ushort value) => (LineBreakClass)(value & ClassMask) switch
    {
        LineBreakClass.AI or LineBreakClass.SG or LineBreakClass.XX => LineBreakClass.AL,
        LineBreakClass.SA => (value & MarkFlag) != 0 ? LineBreakClass.CM : LineBreakClass.AL,
        LineBreakClass.CJ => LineBreakClass.NS,
        var c => c,
    };

    /// <summary>
    /// The one tailoring of a class (UAX #14, 8.1): LISU PUNCTUATION COMMA and FULL STOP (U+A4FE, U+A4FF; BA in LineBreak.txt) as EX — Lisu writes
    /// them after a space, and a line may not begin with them even after it (Unicode 18.9.1). LineBreakTest.txt has neither character.
    /// </summary>
    private static LineBreakClass Tailor(int codePoint, LineBreakClass cls) => codePoint is 0xA4FE or 0xA4FF ? LineBreakClass.EX : cls;

    /// <summary>A Pau Cin Hau tone mark (U+11AE5–U+11AF8): no emergency break before it (Unicode 16.13.1).</summary>
    private static bool IsPauCinHauTone(int codePoint) => codePoint is >= 0x11AE5 and <= 0x11AF8;

    /// <summary>MONGOLIAN VOWEL SEPARATOR: an emergency break goes before it, never after it (Unicode 13.5.1).</summary>
    private const int MongolianVowelSeparator = 0x180E;

    /// <summary>DOTTED CIRCLE, the class [◌] of LB28a.</summary>
    private const int DottedCircle = 0x25CC;

    /// <summary>A unit after LB9: a character with the combining marks and ZWJ it carries (LB9), or a lone one (LB10: as AL).</summary>
    private struct Unit
    {
        public LineBreakClass Class;
        public int Start;
        public int CodePoint;
        public ushort Flags;
        public bool EndsWithJoiner;

        public readonly bool EastAsian => (Flags & EastAsianFlag) != 0;
        public readonly bool Initial => (Flags & PiFlag) != 0;
        public readonly bool Final => (Flags & PfFlag) != 0;
        public readonly bool Pictographic => (Flags & PictographicFlag) != 0;
        public readonly bool Aksara => Class is LineBreakClass.AK or LineBreakClass.AS || CodePoint == DottedCircle;
    }

    /// <summary>The result for one text: per UTF-16 position (0 to the length) the kind of break and whether an emergency break may fall there.</summary>
    internal sealed class Breaks
    {
        private readonly LineBreakKind[] _kinds;
        private readonly bool[] _emergency;

        internal Breaks(LineBreakKind[] kinds, bool[] emergency)
        {
            _kinds = kinds;
            _emergency = emergency;
        }

        /// <summary>The kind of break before the UTF-16 unit <paramref name="position"/> (at the length: the end of the text, LB3).</summary>
        public LineBreakKind Kind(int position) => (uint)position < (uint)_kinds.Length ? _kinds[position] : LineBreakKind.None;

        /// <summary>Whether a line may break before <paramref name="position"/> after the rules (an opportunity or a mandatory break).</summary>
        public bool Allowed(int position) => Kind(position) != LineBreakKind.None;

        /// <summary>Whether an emergency break of a word too wide for its line may fall before <paramref name="position"/>.</summary>
        public bool EmergencyAllowed(int position) => (uint)position < (uint)_emergency.Length && _emergency[position];
    }

    /// <summary>Analyses a text: the break opportunities after UAX #14 and the places of an emergency break.</summary>
    internal static Breaks Analyze(string text)
    {
        var kinds = new LineBreakKind[text.Length + 1];
        var emergency = new bool[text.Length + 1];
        var keep = new bool[text.Length + 1];   // places where an emergency break must not fall either
        var units = new List<Unit>(text.Length);
        // LB1, LB9, LB10: classes per code point, combining marks and ZWJ joined to the character before them
        for (var i = 0; i < text.Length;)
        {
            var cp = TextRunes.RuneAt(text, i).Value;
            var length = char.IsHighSurrogate(text[i]) && i + 1 < text.Length && char.IsLowSurrogate(text[i + 1]) ? 2 : 1;
            var value = ValueOf(cp);
            var cls = Tailor(cp, Resolve(value));
            if (cls is LineBreakClass.CM or LineBreakClass.ZWJ && units.Count > 0
                && units[^1].Class is not (LineBreakClass.BK or LineBreakClass.CR or LineBreakClass.LF or LineBreakClass.NL or LineBreakClass.SP or LineBreakClass.ZW))
            {
                var last = units[^1];
                last.EndsWithJoiner = cls == LineBreakClass.ZWJ;
                units[^1] = last;
            }
            else if (cls is LineBreakClass.CM or LineBreakClass.ZWJ)
                units.Add(new Unit { Class = LineBreakClass.AL, Start = i, CodePoint = cp, EndsWithJoiner = cls == LineBreakClass.ZWJ });
            else
                units.Add(new Unit { Class = cls, Start = i, CodePoint = cp, Flags = (ushort)(value & ~ClassMask) });
            i += length;
        }
        var n = units.Count;
        // NU (SY | IS)* ending at a unit (LB25) and the number of regional indicators in a row ending at it (LB30a)
        var number = new bool[n];
        var indicators = new int[n];
        for (var u = 0; u < n; u++)
        {
            var c = units[u].Class;
            number[u] = c == LineBreakClass.NU || c is LineBreakClass.SY or LineBreakClass.IS && u > 0 && number[u - 1];
            indicators[u] = c == LineBreakClass.RI ? (u > 0 ? indicators[u - 1] : 0) + 1 : 0;
        }
        var lastNonSpace = -1;   // the last unit before the current one that is not SP
        for (var u = 1; u < n; u++)
        {
            if (units[u - 1].Class != LineBreakClass.SP) lastNonSpace = u - 1;
            var (kind, holds) = Decide(units, u, lastNonSpace, number, indicators);
            kinds[units[u].Start] = kind;
            keep[units[u].Start] = holds;
        }
        if (text.Length > 0) kinds[text.Length] = LineBreakKind.Mandatory;   // LB3
        // the boundaries of extended grapheme clusters (UAX #29, from the runtime) less the places the rules keep together
        for (var i = 0; i < text.Length;)
        {
            if (i > 0 && !keep[i])
            {
                var cp = TextRunes.RuneAt(text, i).Value;
                var before = char.IsLowSurrogate(text[i - 1]) && i > 1 ? TextRunes.RuneAt(text, i - 2).Value : text[i - 1];
                emergency[i] = !IsPauCinHauTone(cp) && before != MongolianVowelSeparator;
            }
            i += Math.Max(1, StringInfo.GetNextTextElementLength(text, i));
        }
        if (text.Length > 0) emergency[text.Length] = true;
        return new Breaks(kinds, emergency);
    }

    /// <summary>
    /// The rules LB4–LB31 for the position before unit <paramref name="u"/>: the kind of break, and whether the place belongs to what an
    /// emergency break keeps together (LB8a, LB11, LB28a, LB30a, LB30b).
    /// </summary>
    private static (LineBreakKind Kind, bool Keep) Decide(List<Unit> units, int u, int lastNonSpace, bool[] number, int[] indicators)
    {
        const LineBreakKind no = LineBreakKind.None, yes = LineBreakKind.Allowed;
        var n = units.Count;
        var left = units[u - 1];
        var right = units[u];
        var (l, r) = (left.Class, right.Class);
        var q = lastNonSpace >= 0 ? units[lastNonSpace].Class : LineBreakClass.XX;   // the class before the spaces (SP*)
        var next = u + 1 < n ? units[u + 1].Class : (LineBreakClass?)null;   // after the right unit (null: eot)
        var before = u >= 2 ? units[u - 2].Class : (LineBreakClass?)null;   // before the left unit (null: sot)
        // LB4–LB6: hard line breaks
        if (l == LineBreakClass.BK) return (LineBreakKind.Mandatory, false);
        if (l == LineBreakClass.CR && r == LineBreakClass.LF) return (no, false);
        if (l is LineBreakClass.CR or LineBreakClass.LF or LineBreakClass.NL) return (LineBreakKind.Mandatory, false);
        if (r is LineBreakClass.BK or LineBreakClass.CR or LineBreakClass.LF or LineBreakClass.NL) return (no, false);
        // LB7, LB8, LB8a
        if (r is LineBreakClass.SP or LineBreakClass.ZW) return (no, false);
        if (q == LineBreakClass.ZW) return (yes, false);
        if (left.EndsWithJoiner) return (no, true);
        // LB11, LB12, LB12a
        if (l == LineBreakClass.WJ || r == LineBreakClass.WJ) return (no, true);
        if (l == LineBreakClass.GL) return (no, false);
        if (r == LineBreakClass.GL && l is not (LineBreakClass.SP or LineBreakClass.BA or LineBreakClass.HY)) return (no, false);
        // LB13, LB14
        if (r is LineBreakClass.CL or LineBreakClass.CP or LineBreakClass.EX or LineBreakClass.SY) return (no, false);
        if (q == LineBreakClass.OP) return (no, false);
        // LB15a: an initial quotation mark at the start, after a space, an opening, a quotation mark or GL, even before spaces
        if (q == LineBreakClass.QU && units[lastNonSpace].Initial)
        {
            var b = lastNonSpace >= 1 ? units[lastNonSpace - 1].Class : (LineBreakClass?)null;
            if (b is null or LineBreakClass.BK or LineBreakClass.CR or LineBreakClass.LF or LineBreakClass.NL or LineBreakClass.OP or LineBreakClass.QU
                or LineBreakClass.GL or LineBreakClass.SP or LineBreakClass.ZW) return (no, false);
        }
        // LB15b: a final quotation mark before a space, a prohibited break, a quotation mark or the end
        if (r == LineBreakClass.QU && right.Final && next is null or LineBreakClass.SP or LineBreakClass.GL or LineBreakClass.WJ or LineBreakClass.CL
                or LineBreakClass.QU or LineBreakClass.CP or LineBreakClass.EX or LineBreakClass.IS or LineBreakClass.SY or LineBreakClass.BK
                or LineBreakClass.CR or LineBreakClass.LF or LineBreakClass.NL or LineBreakClass.ZW)
            return (no, false);
        // LB15c, LB15d
        if (l == LineBreakClass.SP && r == LineBreakClass.IS && next == LineBreakClass.NU) return (yes, false);
        if (r == LineBreakClass.IS) return (no, false);
        // LB16, LB17
        if (q is LineBreakClass.CL or LineBreakClass.CP && r == LineBreakClass.NS) return (no, false);
        if (q == LineBreakClass.B2 && r == LineBreakClass.B2) return (no, false);
        // LB18
        if (l == LineBreakClass.SP) return (yes, false);
        // LB19, LB19a
        if (r == LineBreakClass.QU && !right.Initial) return (no, false);
        if (l == LineBreakClass.QU && !left.Final) return (no, false);
        if (r == LineBreakClass.QU && (!left.EastAsian || next is null || !units[u + 1].EastAsian)) return (no, false);
        if (l == LineBreakClass.QU && (!right.EastAsian || before is null || !units[u - 2].EastAsian)) return (no, false);
        // LB20, LB20a
        if (l == LineBreakClass.CB || r == LineBreakClass.CB) return (yes, false);
        if ((l == LineBreakClass.HY || left.CodePoint == 0x2010) && r == LineBreakClass.AL
            && before is null or LineBreakClass.BK or LineBreakClass.CR or LineBreakClass.LF or LineBreakClass.NL or LineBreakClass.SP or LineBreakClass.ZW
                or LineBreakClass.CB or LineBreakClass.GL)
            return (no, false);
        // LB21, LB21a, LB21b, LB22
        if (r is LineBreakClass.BA or LineBreakClass.HY or LineBreakClass.NS || l == LineBreakClass.BB) return (no, false);
        if ((l == LineBreakClass.HY || l == LineBreakClass.BA && !left.EastAsian) && before == LineBreakClass.HL && r != LineBreakClass.HL) return (no, false);
        if (l == LineBreakClass.SY && r == LineBreakClass.HL) return (no, false);
        if (r == LineBreakClass.IN) return (no, false);
        // LB23, LB23a, LB24
        if (l is LineBreakClass.AL or LineBreakClass.HL && r == LineBreakClass.NU || l == LineBreakClass.NU && r is LineBreakClass.AL or LineBreakClass.HL)
            return (no, false);
        if (l == LineBreakClass.PR && r is LineBreakClass.ID or LineBreakClass.EB or LineBreakClass.EM
            || l is LineBreakClass.ID or LineBreakClass.EB or LineBreakClass.EM && r == LineBreakClass.PO)
            return (no, false);
        if (l is LineBreakClass.PR or LineBreakClass.PO && r is LineBreakClass.AL or LineBreakClass.HL
            || l is LineBreakClass.AL or LineBreakClass.HL && r is LineBreakClass.PR or LineBreakClass.PO)
            return (no, false);
        // LB25: numbers
        if (r is LineBreakClass.PO or LineBreakClass.PR
            && (number[u - 1] || l is LineBreakClass.CL or LineBreakClass.CP && u >= 2 && number[u - 2]))
            return (no, false);
        if (l is LineBreakClass.PO or LineBreakClass.PR
            && (r == LineBreakClass.NU
                || r == LineBreakClass.OP && (next == LineBreakClass.NU || next == LineBreakClass.IS && u + 2 < n && units[u + 2].Class == LineBreakClass.NU)))
            return (no, false);
        if (r == LineBreakClass.NU && (l is LineBreakClass.HY or LineBreakClass.IS || number[u - 1])) return (no, false);
        // LB26, LB27: Korean syllable blocks
        if (l == LineBreakClass.JL && r is LineBreakClass.JL or LineBreakClass.JV or LineBreakClass.H2 or LineBreakClass.H3
            || l is LineBreakClass.JV or LineBreakClass.H2 && r is LineBreakClass.JV or LineBreakClass.JT
            || l is LineBreakClass.JT or LineBreakClass.H3 && r == LineBreakClass.JT)
            return (no, false);
        if (l is LineBreakClass.JL or LineBreakClass.JV or LineBreakClass.JT or LineBreakClass.H2 or LineBreakClass.H3 && r == LineBreakClass.PO
            || l == LineBreakClass.PR && r is LineBreakClass.JL or LineBreakClass.JV or LineBreakClass.JT or LineBreakClass.H2 or LineBreakClass.H3)
            return (no, false);
        // LB28, LB28a: letters, orthographic syllables of Brahmic scripts
        if (l is LineBreakClass.AL or LineBreakClass.HL && r is LineBreakClass.AL or LineBreakClass.HL) return (no, false);
        if (l == LineBreakClass.AP && right.Aksara
            || left.Aksara && r is LineBreakClass.VF or LineBreakClass.VI
            || l == LineBreakClass.VI && u >= 2 && units[u - 2].Aksara && (r == LineBreakClass.AK || right.CodePoint == DottedCircle)
            || left.Aksara && right.Aksara && next == LineBreakClass.VF)
            return (no, true);
        // LB29, LB30
        if (l == LineBreakClass.IS && r is LineBreakClass.AL or LineBreakClass.HL) return (no, false);
        if (l is LineBreakClass.AL or LineBreakClass.HL or LineBreakClass.NU && r == LineBreakClass.OP && !right.EastAsian
            || l == LineBreakClass.CP && !left.EastAsian && r is LineBreakClass.AL or LineBreakClass.HL or LineBreakClass.NU)
            return (no, false);
        // LB30a, LB30b
        if (l == LineBreakClass.RI && r == LineBreakClass.RI && indicators[u - 1] % 2 == 1) return (no, true);
        if (r == LineBreakClass.EM && (l == LineBreakClass.EB || left.Pictographic)) return (no, true);
        // LB31
        return (yes, false);
    }
}
