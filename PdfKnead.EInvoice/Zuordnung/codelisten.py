#!/usr/bin/env python3
"""Generates the code table of the e-invoice module (KONZEPT.md, section 5.24, „Codes im Klartext“).

    python PdfKnead.EInvoice/Zuordnung/codelisten.py <folder of the genericode files> [--cldr <folder of the CLDR files>]

Source: the code lists of EN 16931 of the European Commission (Digital Building Blocks, „Registry of supporting artefacts to implement
EN16931“; genericode, the version is in each file; licence per the Commission's legal notice CC BY 4.0, source given in
THIRD-PARTY-NOTICES). The values partly come from other lists (UNTDID, UNECE Rec 20/21, ISO 3166, ISO 4217, ISO/IEC 6523, IANA). Written next
to this script:

    codes.tsv    list  code  name (English, as in the source); the list „1001-Gutschrift“ repeats the credit note types of 1001
    laender.tsv     code  German name  English name — with --cldr, for the codes of the country list
    waehrungen.tsv  code  German name  English name — with --cldr, for the codes of the currency list

The names come from Unicode CLDR (cldr-json; Unicode License v3, given in THIRD-PARTY-NOTICES). The CLDR folder holds
territories-de.json and territories-en.json (cldr-localenames-full), currencies-de.json and currencies-en.json (cldr-numbers-full), and
the package.json of both packages, renamed cldr-localenames-full-package.json and cldr-numbers-full-package.json, for the version.

German names for the common codes are kept by hand in InvoiceCodes.cs. Only the Python standard library.
"""
import json
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
GC = '{http://docs.oasis-open.org/codelist/ns/genericode/1.0/}'


def rows(path):
    data = open(path, 'rb').read()
    if b'<!DOCTYPE' in data or b'<!ENTITY' in data:
        raise SystemExit(f'{path}: DOCTYPE oder ENTITY — nicht gelesen')
    root = ET.fromstring(data)
    version = root.findtext('Identification/Version') or ''
    out = []
    for row in root.iter('Row'):
        values = {v.get('ColumnRef'): ' '.join((v.findtext('SimpleValue') or '').split()) for v in row.iter('Value')}
        code, name, remark = values.get('Code', ''), values.get('Name', ''), values.get('Remark', '')
        if code:
            if '\t' in code + name:
                raise SystemExit(f'{path}: Tabulator in {code}')
            out.append((code, name, remark))
    return version, out


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    folder = sys.argv[1]
    lines, versions = [], []
    for name in sorted(os.listdir(folder)):
        if not name.endswith('.gc'):
            continue
        listname = name[:-3]
        version, entries = rows(os.path.join(folder, name))
        versions.append(f'{listname} {version}')
        lines.extend(f'{listname}\t{code}\t{text}' for code, text, _ in entries)
        if listname == '1001':
            # the credit note types of the list (remark „Credit Note“): UBL takes them in a credit note, the others in an invoice (BR-CL-01)
            lines.extend(f'1001-Gutschrift\t{code}\t{text}' for code, text, remark in entries if remark == 'Credit Note')
    with open(os.path.join(HERE, 'codes.tsv'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('# generated by codelisten.py from the EN 16931 code lists of the European Commission (CC BY 4.0); do not edit by hand\n')
        f.write('# versions: ' + ', '.join(versions) + '\n')
        f.write('# list\tcode\tname\n')
        f.write('\n'.join(lines) + '\n')
    print(f'codes.tsv: {len(lines)} Codes aus {len(versions)} Listen')
    if '--cldr' in sys.argv:
        folder = sys.argv[sys.argv.index('--cldr') + 1]
        codes = {}
        for line in lines:
            listname, code, _ = line.split('\t')
            codes.setdefault(listname, set()).add(code)
        cldr(folder, 'localenames', 'territories', lambda d: d['localeDisplayNames']['territories'], codes['Country'],
             'laender.tsv', 'country names', 'Länder')
        cldr(folder, 'numbers', 'currencies', lambda d: {k: v.get('displayName', '') for k, v in d['numbers']['currencies'].items()},
             codes['Currency'], 'waehrungen.tsv', 'currency names', 'Währungen')
    return 0


def cldr(folder, package, name, pick, codes, out, what, counted):
    """One table of names in German and English from Unicode CLDR for the codes of a list of the Commission."""
    names = {}
    for lang in ('de', 'en'):
        raw = open(os.path.join(folder, f'{name}-{lang}.json'), encoding='utf-8').read()
        names[lang] = pick(json.loads(raw)['main'][lang])
    version = json.loads(open(os.path.join(folder, f'cldr-{package}-full-package.json'), encoding='utf-8').read())['version']
    rows = [(c, names['de'].get(c, ''), names['en'].get(c, '')) for c in sorted(codes)]
    with open(os.path.join(HERE, out), 'w', encoding='utf-8', newline='\n') as f:
        f.write(f'# generated by codelisten.py: {what} from Unicode CLDR {version} (Unicode License v3) for the codes of the EN 16931 list\n')
        f.write('# code\tde\ten\n')
        for c, de, en in rows:
            if any(ch in de + en for ch in '\t\r\n'):
                raise SystemExit(f'Tabulator oder Zeilenumbruch im Namen von {c}')
            f.write(f'{c}\t{de}\t{en}\n')
    print(f'{out}: {len(rows)} {counted} (CLDR {version}), ohne deutschen Namen: {[c for c, de, _ in rows if not de]}')


if __name__ == '__main__':
    sys.exit(main())
